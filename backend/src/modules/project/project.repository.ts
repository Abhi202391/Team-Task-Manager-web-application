// project.repository.ts

import {
  PrismaClient,
} from "@prisma/client";

import {
  CreateProjectDto,
  UpdateProjectDto,
} from "./project.dto";

const prisma =
  new PrismaClient();

export class ProjectRepository {

  //////////////////////////////////////////////////////
  // CREATE PROJECT
  //////////////////////////////////////////////////////

  async create(
    data: CreateProjectDto,
    createdById: string
  ) {

    return prisma.project.create({

      data: {

        ...data,

        createdById,

        //////////////////////////////////////////////////////
        // ADD CREATOR AS MEMBER
        //////////////////////////////////////////////////////

        members: {

          create: {

            userId:
              createdById,
          },
        },
      },

      include: {

        //////////////////////////////////////////////////////
        // CREATOR
        //////////////////////////////////////////////////////

        creator: true,

        //////////////////////////////////////////////////////
        // PROJECT MEMBERS
        //////////////////////////////////////////////////////

        members: {

          include: {

            user: true,
          },
        },

        //////////////////////////////////////////////////////
        // PROJECT TASKS
        //////////////////////////////////////////////////////

        tasks: {

          include: {

            //////////////////////////////////////////////////////
            // TASK ASSIGNEES
            //////////////////////////////////////////////////////

            assignees: {

              include: {

                user: true,
              },
            },

            //////////////////////////////////////////////////////
            // TASK CREATOR
            //////////////////////////////////////////////////////

            createdBy: true,

            //////////////////////////////////////////////////////
            // TASK ATTACHMENTS
            //////////////////////////////////////////////////////

            attachments: true,
          },
        },
      },
    });
  }

  //////////////////////////////////////////////////////
  // GET ALL PROJECTS
  //////////////////////////////////////////////////////

  async findAll() {

    return prisma.project.findMany({

      include: {

        //////////////////////////////////////////////////////
        // CREATOR
        //////////////////////////////////////////////////////

        creator: true,

        //////////////////////////////////////////////////////
        // MEMBERS
        //////////////////////////////////////////////////////

        members: {

          include: {

            user: true,
          },
        },

        //////////////////////////////////////////////////////
        // TASKS
        //////////////////////////////////////////////////////

        tasks: {

          include: {

            assignees: {

              include: {

                user: true,
              },
            },

            createdBy: true,

            attachments: true,
          },
        },
      },
    });
  }

  //////////////////////////////////////////////////////
  // GET PROJECT BY ID
  //////////////////////////////////////////////////////

  async findById(
    id: string
  ) {

    return prisma.project.findUnique({

      where: { id },

      include: {

        //////////////////////////////////////////////////////
        // CREATOR
        //////////////////////////////////////////////////////

        creator: true,

        //////////////////////////////////////////////////////
        // MEMBERS
        //////////////////////////////////////////////////////

        members: {

          include: {

            user: true,
          },
        },

        //////////////////////////////////////////////////////
        // TASKS
        //////////////////////////////////////////////////////

        tasks: {

          include: {

            //////////////////////////////////////////////////////
            // TASK ASSIGNEES
            //////////////////////////////////////////////////////

            assignees: {

              include: {

                user: true,
              },
            },

            //////////////////////////////////////////////////////
            // CREATED BY
            //////////////////////////////////////////////////////

            createdBy: true,

            //////////////////////////////////////////////////////
            // ATTACHMENTS
            //////////////////////////////////////////////////////

            attachments: true,
          },
        },
      },
    });
  }

  //////////////////////////////////////////////////////
  // UPDATE PROJECT
  //////////////////////////////////////////////////////

  async update(
    id: string,
    data: UpdateProjectDto
  ) {

    return prisma.project.update({

      where: { id },

      data,
    });
  }

  //////////////////////////////////////////////////////
  // DELETE PROJECT
  //////////////////////////////////////////////////////

  async delete(
    id: string
  ) {

    return prisma.project.delete({

      where: { id },
    });
  }

  //////////////////////////////////////////////////////
  // ADD MEMBER
  //////////////////////////////////////////////////////

  async addMember(
    projectId: string,
    userId: string
  ) {

    return prisma.projectMember.create({

      data: {

        projectId,

        userId,
      },
    });
  }

  //////////////////////////////////////////////////////
  // CHECK MEMBER
  //////////////////////////////////////////////////////

  async findMember(
    projectId: string,
    userId: string
  ) {

    return prisma.projectMember.findUnique({

      where: {

        projectId_userId: {

          projectId,

          userId,
        },
      },
    });
  }

  //////////////////////////////////////////////////////
  // REMOVE MEMBER
  //////////////////////////////////////////////////////

  async removeMember(
    projectId: string,
    userId: string
  ) {

    return prisma.projectMember.delete({

      where: {

        projectId_userId: {

          projectId,

          userId,
        },
      },
    });
  }
}